bool RangeContains(const std::uint32_t rangeRva,
                   const std::uint32_t rangeSize,
                   const std::uint32_t itemRva,
                   const std::size_t itemSize) noexcept {
    if (itemSize > UINT32_MAX) {
        return false;
    }
    const std::uint32_t size = static_cast<std::uint32_t>(itemSize);
    return itemRva >= rangeRva && itemRva - rangeRva <= rangeSize &&
           size <= rangeSize - (itemRva - rangeRva);
}

template <std::size_t Size>
bool ValidateSignature(const target::HostImage& image,
                       const Code<Size>& code) noexcept {
    if (!RangeContains(image.textRva, image.textSize, code.rva,
                       code.signature.size()) ||
        image.imageBase == 0) {
        return false;
    }
    const auto* const address =
        reinterpret_cast<const void*>(image.imageBase + code.rva);
    return std::memcmp(address, code.signature.data(),
                       code.signature.size()) == 0;
}

const Layout* LayoutFor(const target::KnownBuild& build) noexcept {
    switch (build.id) {
    case target::BuildId::gog_57301760292462330:
        return &kGogLayout;
    case target::BuildId::steam_13346472:
        return &kSteamLayout;
    default:
        return nullptr;
    }
}

std::wstring MismatchAt(const wchar_t* const what, const std::uint32_t rva) {
    wchar_t text[160]{};
    swprintf_s(text, L"%ls signature mismatch at RVA 0x%08X", what, rva);
    return text;
}

