// Where each function and global the fix uses lives in one executable
// build, with the leading code bytes that must be found there before it is
// used. A signature has the same length in every build; its bytes differ
// between builds where the code holds a relative displacement. RVAs named
// in the comments below are the GOG build's.
template <std::size_t Size>
struct Code {
    std::uint32_t rva = 0;
    std::array<std::uint8_t, Size> signature{};
};

struct Layout {
    Code<9> steadySwapWrapper;
    Code<31> logicTimerWantUpdate;
    Code<20> updaterDispatch;
    Code<25> engineMicrosecondClock;
    // cEngine::SetUpdatesPerSec(rate, catchUpDivisor): loads the logic timer
    // from engine+0x48 and tail-calls the timer's own setter at RVA 0x00555530.
    Code<9> engineSetUpdatesPerSec;
    Code<32> logicTimerSetUpdatesPerSec;
    // iRenderable::GetMatrixUpdateCount as implemented for entity-backed
    // renderables: `add rcx,78h; jmp` to the transform update-count getter.
    Code<16> renderableGetMatrixUpdateCount;
    // cImGui, the script-driven GUI behind the menus and the inventory. Its
    // script pass stores draw commands once per tick in the vector at +0x300
    // (0xA0 bytes each, position at +0x08); Draw replays them every frame.
    // DoMouse and End queue the cursor at the mouse position held at +0x4E50,
    // which SendMousePosition fills from the pixel position the game read.
    Code<32> imGuiDraw;
    Code<32> imGuiDoMouse;
    Code<32> imGuiEnd;
    Code<32> imGuiSendMousePosition;
    Code<32> imGuiSendMouseVirtualPosition;
    // iParticleEmitter's per-view graphics update (vtable slot +0x68, shared by
    // cParticleEmitter_UserData): builds the vertices from the live particle
    // list at +0x1E8 (count at +0x200). Each cParticle starts with its position
    // and, at +0x0C, the position before the last motion update.
    Code<32> particleUpdateGraphics;
    Code<7> entityGetTransformUpdateCount;
    // cLightSpot::GetViewProjMatrix: returns the cached
    // bias * projection * inverse(world) at light+0x408, used for shadow and
    // gobo projection. The bias matrix is the constant at RVA 0x0094C070.
    Code<32> lightSpotGetViewProjMatrix;
    Code<32> lightSpotGetProjectionMatrix;
    std::uint32_t lightProjectionBiasMatrixRva = 0;
    // cLightSpot::GetViewMatrix: cached inverse(world) at light+0x448.
    Code<32> lightSpotGetViewMatrix;
    // cLightSpot::GetFrustum: rebuilds the frustum at light+0x4C8 from the view
    // and projection matrices when the transform count differs from the tag at
    // light+0x4FC. The shadow map is drawn through this frustum.
    Code<32> lightSpotGetFrustum;
    // Renderer decision whether a light's cached shadow map must be redrawn:
    // (renderer, light, shadowData, casterList, cacheUsable, flag) -> bool.
    // Its single call site is at RVA 0x00584F99.
    Code<32> shadowMapNeedsUpdate;
    Code<8> limitFpsGetter;
    std::uint32_t engineGlobalPointerRva = 0;
    std::uint32_t sceneGlobalPointerRva = 0;
    Code<24> sceneSetCurrentListener;
    Code<23> viewportSetCamera;
    Code<5> cameraGetPosition;
    Code<16> cameraSetPitch;
    Code<16> cameraSetYaw;
    Code<21> cameraSetRoll;
    Code<32> cameraSetPosition;
    Code<32> cameraGetViewMatrix;
    Code<27> cameraGetMoveMatrix;
    Code<32> cameraGetFrustum;
    Code<32> cameraGetExtendedFrustum;
    Code<32> sceneRenderAll;
    Code<32> entitySetMatrix;
    Code<32> entityUpdateAttachment;
    Code<16> subMeshGetModelMatrix;
    Code<20> subMeshGetSkinningPalette;
    Code<32> subMeshUpdateSkinning;
    Code<32> meshUpdatePalette;
};

