bool ResolveTelemetryMap(const target::HostImage& image,
                         const target::KnownBuild& build,
                         TelemetryMap& map,
                         std::wstring& error) noexcept {
    map = {};
    error.clear();
    const Layout* const layout = LayoutFor(build);
    if (layout == nullptr) {
        error = L"No telemetry mapping exists for this executable build";
        return false;
    }
    if (!ValidateSignature(image, layout->steadySwapWrapper)) {
        error = MismatchAt(L"Steady swap wrapper",
                           layout->steadySwapWrapper.rva);
        return false;
    }
    if (!ValidateSignature(image, layout->logicTimerWantUpdate)) {
        error = MismatchAt(L"Logic timer WantUpdate",
                           layout->logicTimerWantUpdate.rva);
        return false;
    }
    if (!ValidateSignature(image, layout->updaterDispatch)) {
        error = MismatchAt(L"Updater dispatch", layout->updaterDispatch.rva);
        return false;
    }
    if (!ValidateSignature(image, layout->engineMicrosecondClock)) {
        error = MismatchAt(L"Engine microsecond clock",
                           layout->engineMicrosecondClock.rva);
        return false;
    }
    if (!ValidateSignature(image, layout->limitFpsGetter)) {
        error = MismatchAt(L"LimitFPS getter", layout->limitFpsGetter.rva);
        return false;
    }
    if (!RangeContains(0, image.imageSize, layout->engineGlobalPointerRva,
                       sizeof(std::uintptr_t))) {
        error = L"Engine global pointer is outside the mapped image";
        return false;
    }
    map.steadySwapWrapper = image.imageBase + layout->steadySwapWrapper.rva;
    map.logicTimerWantUpdate =
        image.imageBase + layout->logicTimerWantUpdate.rva;
    map.updaterDispatch = image.imageBase + layout->updaterDispatch.rva;
    map.engineMicrosecondClock =
        image.imageBase + layout->engineMicrosecondClock.rva;
    map.limitFpsGetter = image.imageBase + layout->limitFpsGetter.rva;
    map.engineGlobalPointer = image.imageBase + layout->engineGlobalPointerRva;
    return true;
}

bool ResolveWorldMap(const target::HostImage& image,
                     const target::KnownBuild& build,
                     TelemetryMap& map,
                     std::wstring& error) noexcept {
    map.renderableGetMatrixUpdateCount = 0;
    map.lightSpotGetViewProjMatrix = 0;
    map.lightSpotGetProjectionMatrix = 0;
    map.lightProjectionBiasMatrix = 0;
    map.shadowMapNeedsUpdate = 0;
    map.lightSpotGetViewMatrix = 0;
    map.lightSpotGetFrustum = 0;
    error.clear();
    const Layout* const layout = LayoutFor(build);
    if (layout == nullptr) {
        error = L"No world-object mapping exists for this executable build";
        return false;
    }
    if (!ValidateSignature(image, layout->renderableGetMatrixUpdateCount) ||
        !ValidateSignature(image, layout->entityGetTransformUpdateCount)) {
        error = MismatchAt(L"Renderable matrix update-count",
                           layout->renderableGetMatrixUpdateCount.rva);
        return false;
    }
    if (!ValidateSignature(image, layout->lightSpotGetViewProjMatrix) ||
        !ValidateSignature(image, layout->lightSpotGetProjectionMatrix) ||
        !ValidateSignature(image, layout->shadowMapNeedsUpdate) ||
        !ValidateSignature(image, layout->lightSpotGetViewMatrix) ||
        !ValidateSignature(image, layout->lightSpotGetFrustum) ||
        !RangeContains(0, image.imageSize,
                       layout->lightProjectionBiasMatrixRva,
                       16 * sizeof(float))) {
        error = MismatchAt(L"Spot-light projection",
                           layout->lightSpotGetViewProjMatrix.rva);
        return false;
    }
    map.renderableGetMatrixUpdateCount =
        image.imageBase + layout->renderableGetMatrixUpdateCount.rva;
    map.lightSpotGetViewProjMatrix =
        image.imageBase + layout->lightSpotGetViewProjMatrix.rva;
    map.lightSpotGetProjectionMatrix =
        image.imageBase + layout->lightSpotGetProjectionMatrix.rva;
    map.lightProjectionBiasMatrix =
        image.imageBase + layout->lightProjectionBiasMatrixRva;
    map.shadowMapNeedsUpdate =
        image.imageBase + layout->shadowMapNeedsUpdate.rva;
    map.lightSpotGetViewMatrix =
        image.imageBase + layout->lightSpotGetViewMatrix.rva;
    map.lightSpotGetFrustum = image.imageBase + layout->lightSpotGetFrustum.rva;
    return true;
}

